class Usuario {
    constructor(
      Email,
      Password,
      Nombre,
      Imagen,
      Descripcion,
      Departamento,
    ) 
    {
      this.Email = Email;
      this.Password = Password;
      this.Nombre = Nombre;
      this.Imagen = Imagen;
      this.Descripcion = Descripcion;
      this.Departamento = Departamento;
    }
  }
  
  export default Usuario;